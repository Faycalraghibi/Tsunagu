"""Generate the numbers in results/results.md (AUTO block only) and factual observations."""

from __future__ import annotations

import math
from pathlib import Path
from typing import Any

from tsunagu.metrics import percentile, wilson_interval

TYPES = ("single_fact", "multi_hop", "relational", "exact_reference", "unanswerable")
AUTO_START = "<!-- AUTO:START (generated by `tsunagu report`; do not edit by hand) -->"
AUTO_END = "<!-- AUTO:END -->"
MANUAL_TEMPLATE = """

## Findings

_To be written by the owner from the tables above: 3 to 5 honest bullets, including where the graph lost._

## Limits

_To be written by the owner: corpus size, 30 questions, one LLM for extraction, answers and judge, judge bias._

## What I would do at Safran

_To be written by the owner: 5 lines._
"""


def _mean(values: list[float]) -> float:
    return sum(values) / len(values) if values else float("nan")


def _f(x: float | None, digits: int = 2) -> str:
    return "n/a" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.{digits}f}"


def _pct(x: float) -> str:
    return "n/a" if math.isnan(x) else f"{100 * x:.0f}%"


def _systems(rows: list[dict[str, Any]]) -> list[str]:
    return list(dict.fromkeys(r["system"] for r in rows))


def question_outcomes(rows: list[dict[str, Any]], system: str) -> dict[str, dict[str, Any]]:
    """Per question: majority pass (score 2), mean score, stability across repeats."""
    by_q: dict[str, dict[str, Any]] = {}
    for r in rows:
        if r["system"] != system or r["correctness"] is None:
            continue
        entry = by_q.setdefault(r["qid"], {"type": r["type"], "scores": []})
        entry["scores"].append(r["correctness"])
    for entry in by_q.values():
        scores = entry["scores"]
        entry["passed"] = sum(1 for s in scores if s == 2) > len(scores) / 2
        entry["mean_score"] = _mean(scores)
        entry["stable"] = len(set(scores)) == 1
    return by_q


def _pass_cell(outcomes: dict[str, dict[str, Any]], types: tuple[str, ...]) -> tuple[str, int, int]:
    selected = [o for o in outcomes.values() if o["type"] in types]
    k, n = sum(1 for o in selected if o["passed"]), len(selected)
    if n == 0:
        return "n/a", 0, 0
    lo, hi = wilson_interval(k, n)
    return f"{k}/{n} = {_pct(k / n)} [{_pct(lo)}, {_pct(hi)}]", k, n


def retrieval_section(rows: list[dict[str, Any]], systems: list[str]) -> str:
    base = [r for r in rows if r["repeat"] == 0 and r["type"] != "unanswerable"]
    lines = [
        "### Retrieval (hit@8 / recall@8 / MRR, page level)",
        "",
        "| Type | " + " | ".join(systems) + " |",
        "|---|" + "---|" * len(systems),
    ]
    for qtype in (*TYPES[:-1], "all"):
        sel = [r for r in base if qtype == "all" or r["type"] == qtype]
        n = len({r["qid"] for r in sel})
        cells = []
        for s in systems:
            mine = [r for r in sel if r["system"] == s]
            cells.append(
                f"{_f(_mean([r['hit'] for r in mine]))} / {_f(_mean([r['recall'] for r in mine]))} / {_f(_mean([r['mrr'] for r in mine]))}"
            )
        lines.append(f"| {qtype} (n={n}) | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def correctness_section(rows: list[dict[str, Any]], systems: list[str]) -> str:
    outcomes = {s: question_outcomes(rows, s) for s in systems}
    lines = [
        "### Correctness (judge score 2 in a majority of repeats), 95% Wilson CI, n = questions",
        "",
        "| Type | " + " | ".join(systems) + " |",
        "|---|" + "---|" * len(systems),
    ]
    groups: list[tuple[str, tuple[str, ...]]] = [(t, (t,)) for t in TYPES]
    groups += [("answerable", TYPES[:-1]), ("all", TYPES)]
    for label, types in groups:
        lines.append(
            f"| {label} | " + " | ".join(_pass_cell(outcomes[s], types)[0] for s in systems) + " |"
        )
    mean_cells = [_f(_mean([o["mean_score"] for o in outcomes[s].values()])) for s in systems]
    stable_cells = [
        _pct(_mean([float(o["stable"]) for o in outcomes[s].values()])) for s in systems
    ]
    lines.append("| mean score (0 to 2) | " + " | ".join(mean_cells) + " |")
    lines.append("| repeat stability | " + " | ".join(stable_cells) + " |")
    return "\n".join(lines)


def generation_section(rows: list[dict[str, Any]], systems: list[str]) -> str:
    lines = [
        "### Faithfulness, citation precision, abstention (pooled over repeats)",
        "",
        "| Metric | " + " | ".join(systems) + " |",
        "|---|" + "---|" * len(systems),
    ]
    metrics: dict[str, list[str]] = {
        "faithfulness (supported claims)": [],
        "citation precision": [],
        "correct abstention (unanswerable)": [],
        "false abstention (answerable)": [],
        "JSON parse failures": [],
        "judge unparseable": [],
    }
    for s in systems:
        mine = [r for r in rows if r["system"] == s and r.get("parse_ok") is not None]
        judged = [r for r in mine if r["type"] != "unanswerable" and not r["abstained"]]
        claims = sum(r["claims_total"] or 0 for r in judged)
        supported = sum(r["claims_supported"] or 0 for r in judged)
        cited = sum(r["cited_pages"] or 0 for r in judged)
        precise = sum(r["precise_citations"] or 0 for r in judged)
        unans = [r for r in mine if r["type"] == "unanswerable"]
        answ = [r for r in mine if r["type"] != "unanswerable"]
        metrics["faithfulness (supported claims)"].append(
            f"{supported}/{claims} = {_pct(supported / claims if claims else float('nan'))}"
        )
        metrics["citation precision"].append(
            f"{precise}/{cited} = {_pct(precise / cited if cited else float('nan'))}"
        )
        metrics["correct abstention (unanswerable)"].append(
            _pct(_mean([float(bool(r["abstained"])) for r in unans]))
        )
        metrics["false abstention (answerable)"].append(
            _pct(_mean([float(bool(r["abstained"])) for r in answ]))
        )
        metrics["JSON parse failures"].append(str(sum(1 for r in mine if r["parse_ok"] is False)))
        metrics["judge unparseable"].append(
            str(sum(1 for r in mine if str(r.get("judge_reason", "")).startswith("unparseable")))
        )
    for name, cells in metrics.items():
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def ops_section(rows: list[dict[str, Any]], systems: list[str]) -> str:
    lines = [
        "### Latency and tokens per query",
        "",
        "| Metric | " + " | ".join(systems) + " |",
        "|---|" + "---|" * len(systems),
    ]
    cells: dict[str, list[str]] = {
        k: []
        for k in (
            "retrieval p50 / p95 (ms)",
            "end-to-end p50 / p95 (s)",
            "answer tokens per query (in + out)",
            "graph candidate pool (mean chunks)",
            "graph dense fallback (chunks, total)",
        )
    }
    for s in systems:
        mine = [r for r in rows if r["system"] == s and r["answer_latency_s"] is not None]
        retr = [r["retrieval_latency_s"] * 1000 for r in mine]
        e2e = [r["retrieval_latency_s"] + r["answer_latency_s"] for r in mine]
        tokens = [r["answer_prompt_tokens"] + r["answer_completion_tokens"] for r in mine]
        pools = [r["graph_pool_size"] for r in mine if r["graph_pool_size"] is not None]
        cells["retrieval p50 / p95 (ms)"].append(
            f"{_f(percentile(retr, 50), 0)} / {_f(percentile(retr, 95), 0)}"
        )
        cells["end-to-end p50 / p95 (s)"].append(
            f"{_f(percentile(e2e, 50), 1)} / {_f(percentile(e2e, 95), 1)}"
        )
        cells["answer tokens per query (in + out)"].append(_f(_mean([float(t) for t in tokens]), 0))
        cells["graph candidate pool (mean chunks)"].append(
            _f(_mean([float(p) for p in pools]), 0) if pools else "n/a"
        )
        fallback = [
            r["graph_fallback"]
            for r in mine
            if r["graph_fallback"] is not None and r["repeat"] == 0
        ]
        cells["graph dense fallback (chunks, total)"].append(
            str(sum(fallback)) if fallback else "n/a"
        )
    for name, row in cells.items():
        lines.append(f"| {name} | " + " | ".join(row) + " |")
    return "\n".join(lines)


def header_section(
    corpus: dict[str, Any],
    graph_stats: dict[str, Any],
    indexing: dict[str, Any],
    usage: dict[str, dict[str, float]],
    review: tuple[int, int] | None,
    questions_changed: bool,
) -> str:
    before = graph_stats.get("before_resolution", {})
    after = graph_stats.get("after_resolution", {})
    extraction = usage.get("extraction", {})
    tokens = int(extraction.get("prompt_tokens", 0) + extraction.get("completion_tokens", 0))
    review_text = (
        f"{review[1]}/{review[0]} reviewed"
        if review and review[0]
        else "PENDING (merges_review.csv not filled)"
    )
    lines = [
        f"Corpus: LangGraph docs @ `{corpus.get('commit', '?')[:12]}`, {corpus.get('n_pages')} pages, "
        f"{corpus.get('n_tokens')} tokens (cl100k), {corpus.get('n_chunks')} chunks",
        f"Graph: {before.get('entities')} entities before / {after.get('entities')} after resolution "
        f"({before.get('llm_entities')} LLM entities before, {after.get('llm_entities')} after), "
        f"{after.get('llm_relations')} LLM relations, {after.get('explicit_links')} explicit links; "
        f"merges {graph_stats.get('merges_by_reason', {})}; false merges found: {review_text}",
        f"Indexing: {tokens} LLM tokens over {int(extraction.get('calls', 0))} extraction calls, "
        f"{extraction.get('latency_s', 0.0) / 60:.1f} min of LLM time (extraction model: {indexing.get('extraction_model')}, "
        f"backend: {indexing.get('extraction_backend')}); dense index {indexing.get('dense_index_seconds')} s "
        f"({indexing.get('embed_model')}); chunks without triplets: {indexing.get('chunks_without_triplets')}/{indexing.get('chunks_extracted')}",
    ]
    if questions_changed:
        lines.append("WARNING: data/questions.jsonl changed after the first eval run.")
    return "\n\n".join(lines)


def calibration_section(calib: dict[str, Any] | None) -> str:
    if not calib or not calib.get("n"):
        return "Judge calibration: PENDING (data/labels_manual.csv not labelled yet)."
    return (
        f"Judge calibration: agreement {_pct(calib['agreement'])}, kappa {calib['kappa']:.2f} on {calib['n']} labels "
        f"(pass/fail view: agreement {_pct(calib['agreement_pass'])}, kappa {calib['kappa_pass']:.2f})."
    )


def render_auto(
    rows: list[dict[str, Any]], header: str, calib: dict[str, Any] | None, repeats: int
) -> str:
    systems = _systems(rows)
    n_q = len({r["qid"] for r in rows})
    note = (
        f"Statistics: {n_q} questions, {repeats} repeat(s) per system. With about 30 questions, differences under "
        "about 15 points are probably noise; per-type n is 3 to 8, so per-type rates are indicative only."
    )
    parts = [header, retrieval_section(rows, systems), correctness_section(rows, systems)]
    parts += [
        generation_section(rows, systems),
        ops_section(rows, systems),
        calibration_section(calib),
        note,
    ]
    return "\n\n".join(parts)


def observations(rows: list[dict[str, Any]], systems: list[str]) -> str:
    """Facts only: best system per type and whether the Wilson intervals overlap."""
    outcomes = {s: question_outcomes(rows, s) for s in systems}
    lines = ["# Observations (generated facts, not conclusions)", ""]
    for qtype in (*TYPES, "answerable"):
        types = TYPES[:-1] if qtype == "answerable" else (qtype,)
        stats = []
        for s in systems:
            _, k, n = _pass_cell(outcomes[s], types)
            if n:
                stats.append((k / n, s, wilson_interval(k, n)))
        if len(stats) < 2:
            continue
        stats.sort(reverse=True)
        (best_rate, best, best_ci), (second_rate, second, second_ci) = stats[0], stats[1]
        overlap = best_ci[0] <= second_ci[1]
        verdict = (
            "intervals overlap: not distinguishable at this n"
            if overlap
            else "intervals do not overlap"
        )
        lines.append(
            f"- {qtype}: highest pass rate {best} {_pct(best_rate)}, next {second} {_pct(second_rate)}; {verdict}."
        )
    return "\n".join(lines) + "\n"


def write_results(path: Path, auto_md: str) -> None:
    """Replace the AUTO block in results.md, creating the file with owner sections if missing."""
    block = f"{AUTO_START}\n\n{auto_md}\n\n{AUTO_END}"
    if path.exists():
        text = path.read_text(encoding="utf-8")
        if AUTO_START in text and AUTO_END in text:
            head, rest = text.split(AUTO_START, 1)
            _, tail = rest.split(AUTO_END, 1)
            path.write_text(head + block + tail, encoding="utf-8")
            return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("# Tsunagu results\n\n" + block + MANUAL_TEMPLATE, encoding="utf-8")


LATEX_SPECIALS = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def latex_escape(text: str) -> str:
    """Escape LaTeX special characters; `code` spans become \texttt."""
    parts = text.split("`")
    out = []
    for i, part in enumerate(parts):
        escaped = "".join(LATEX_SPECIALS.get(ch, ch) for ch in part)
        out.append(rf"\texttt{{{escaped}}}" if i % 2 else escaped)
    return "".join(out)


def _table_to_latex(lines: list[str]) -> str:
    rows = [[cell.strip() for cell in line.strip().strip("|").split("|")] for line in lines]
    header, body = rows[0], rows[2:]
    spec = "l" + "r" * (len(header) - 1)
    out = [r"\begin{center}", rf"\begin{{tabular}}{{{spec}}}", r"\toprule"]
    out.append(" & ".join(latex_escape(c) for c in header) + r" \\")
    out.append(r"\midrule")
    out += [" & ".join(latex_escape(c) for c in row) + r" \\" for row in body]
    out += [r"\bottomrule", r"\end{tabular}", r"\end{center}"]
    return "\n".join(out)


def auto_to_latex(auto_md: str) -> str:
    """Convert generated Markdown (paragraphs, headings, bullets, tables) to LaTeX."""
    blocks = []
    for block in auto_md.strip().split("\n\n"):
        lines = block.strip().splitlines()
        if not lines:
            continue
        if lines[0].startswith("# "):
            continue
        if lines[0].startswith("- "):
            items = [rf"\item {latex_escape(line[2:])}" for line in lines]
            blocks.append("\n".join([r"\begin{itemize}", *items, r"\end{itemize}"]))
        elif lines[0].startswith("### "):
            blocks.append(rf"\subsection*{{{latex_escape(lines[0][4:])}}}")
        elif lines[0].startswith("|"):
            blocks.append(_table_to_latex(lines))
        else:
            blocks.append(latex_escape(" ".join(lines)))
    return "\n\n".join(blocks) + "\n"
